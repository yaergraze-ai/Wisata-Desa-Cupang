import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, "src");
const BI_CSS_PATH = path.join(
  ROOT,
  "node_modules",
  "bootstrap-icons",
  "font",
  "bootstrap-icons.css"
);
const OUT_CSS_PATH = path.join(ROOT, "src", "styles", "bootstrap-icons-swap.css");

function walkFiles(dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkFiles(full));
    } else if (/\.(tsx|ts)$/.test(entry.name)) {
      results.push(full);
    }
  }
  return results;
}

const usedIcons = new Set();
for (const file of walkFiles(SRC_DIR)) {
  const content = fs.readFileSync(file, "utf8");
  const matches = content.match(/\bbi-[a-z0-9-]+\b/g);
  if (matches) {
    for (const m of matches) {
      usedIcons.add(m);
    }
  }
}

const rawBiCss = fs.readFileSync(BI_CSS_PATH, "utf8");
const ruleRegex = /\.bi-([a-z0-9-]+)::before\s*\{\s*content:\s*"([^"]+)";\s*\}/g;
const matchedRules = [];

let match;
while ((match = ruleRegex.exec(rawBiCss)) !== null) {
  const className = `bi-${match[1]}`;
  if (usedIcons.has(className)) {
    matchedRules.push(`.${className}::before { content: "${match[2]}"; }`);
  }
}

const output = `/* Auto-generated by scripts/build-icons-css.mjs from bootstrap-icons@1.13.2 */
@font-face {
  font-display: swap;
  font-family: "bootstrap-icons";
  src: url("/fonts/bootstrap-icons.woff2") format("woff2"),
       url("/fonts/bootstrap-icons.woff") format("woff");
}

.bi::before {
  display: inline-block;
  font-family: bootstrap-icons !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${matchedRules.join("\n")}
`;

fs.writeFileSync(OUT_CSS_PATH, output, "utf8");
console.log(
  `OK: bootstrap-icons-swap.css dibangun (${matchedRules.length} ikon aktif, ${(
    Buffer.byteLength(output) / 1024
  ).toFixed(1)} KB).`
);
